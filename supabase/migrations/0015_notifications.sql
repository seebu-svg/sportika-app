-- Sportika in-app notification module: one inbox table, per-member delivery
-- preferences, event triggers and the member-facing read/mark RPCs.
--
-- Design rules inherited from 0003/0006/0007:
--   * RLS is enabled but never forced, so security-definer triggers and RPCs can
--     write while anon/authenticated clients stay policy-gated.
--   * Every member-facing mutation is an RPC that derives the subject from
--     auth.uid(). There is no account-id parameter anywhere.
--   * Members hold SELECT only. Notification content and recipient can only be
--     written by the server, never by a client.
--
-- Notifications are generated by triggers on the aggregate tables, so a
-- notification and the business change it describes commit or roll back
-- together. An operation that raises never leaves a notification behind.
--
-- Teams remain device-local in this MVP (there is no teams table in the live
-- schema), so team activity notifications are produced by the device store and
-- are documented as such; everything else here is server generated.
begin;

-- ════════════════════════════════════════════════════════════════════════════
-- 1.  notifications
-- ════════════════════════════════════════════════════════════════════════════
create table if not exists public.notifications (
  id           uuid primary key default gen_random_uuid(),
  recipient_id uuid not null references public.profiles (id) on delete cascade,
  actor_id     uuid references public.profiles (id) on delete set null,

  -- match | scorer | tournament | dispute | team | account | platform.
  -- The category decides which preference switch gates delivery.
  category     text not null default 'platform',

  -- Stable machine type, e.g. match_invite or tournament_registration_confirmed.
  type         text not null,

  title        text not null,
  body         text not null default '',

  -- What the notification points at, so the client can validate the destination
  -- before navigating. The client never trusts a raw path from here.
  entity_type  text,
  entity_id    text,

  -- Structured, allow-listed navigation data (ids only, never a URL).
  payload      jsonb not null default '{}'::jsonb,

  read_at      timestamptz,
  expires_at   timestamptz,
  created_at   timestamptz not null default now(),

  -- Deterministic key for one business event. The partial unique index below
  -- makes redelivery idempotent: the same event can never land twice.
  event_key    text,

  constraint notifications_category check (
    category in ('match', 'scorer', 'tournament', 'dispute', 'team',
                 'account', 'platform')),
  constraint notifications_type_len   check (char_length(type) between 1 and 60),
  constraint notifications_title_len  check (char_length(title) between 1 and 120),
  constraint notifications_body_len   check (char_length(body) <= 400),
  constraint notifications_entity     check (
    entity_type is null
    or entity_type in ('match', 'result', 'tournament', 'fixture', 'team',
                       'dispute', 'account')),
  constraint notifications_payload    check (jsonb_typeof(payload) = 'object'),
  constraint notifications_event_key  check (
    event_key is null or char_length(event_key) between 1 and 200)
);

comment on table public.notifications is
  'Per-member in-app inbox. Written only by security-definer triggers and RPCs.';
comment on column public.notifications.event_key is
  'Idempotency key for one business event; unique per recipient when present.';

alter table public.notifications enable row level security;
revoke all on public.notifications from public, anon, authenticated;
grant select on public.notifications to authenticated;

drop policy if exists notifications_select_own on public.notifications;
create policy notifications_select_own on public.notifications
  for select to authenticated
  using (recipient_id = auth.uid());

-- Feed page: newest first, keyset-paginated by (created_at, id).
create index if not exists notifications_recipient_created
  on public.notifications (recipient_id, created_at desc, id desc);
-- Unread badge: partial, so the count never touches read rows.
create index if not exists notifications_recipient_unread
  on public.notifications (recipient_id, created_at desc)
  where read_at is null;
create index if not exists notifications_recipient_category
  on public.notifications (recipient_id, category, created_at desc);
create unique index if not exists notifications_event_key_unique
  on public.notifications (recipient_id, event_key)
  where event_key is not null;

-- Realtime is how an open app paints a new notification and a second device
-- sees a read. The publication carries the table; the policy above is what
-- limits each member to their own rows.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (
       select 1
         from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'notifications'
     ) then
    alter publication supabase_realtime add table public.notifications;
  end if;
end $$;

-- ════════════════════════════════════════════════════════════════════════════
-- 2.  delivery preferences
-- ════════════════════════════════════════════════════════════════════════════
-- Optional categories can be switched off. Account and security messages have
-- no switch: they stay deliverable in-app by design.
create table if not exists public.notification_preferences (
  profile_id             uuid primary key
                         references public.profiles (id) on delete cascade,
  match_activity         boolean not null default true,
  tournament_updates     boolean not null default true,
  team_activity          boolean not null default true,
  scorer_assignments     boolean not null default true,
  platform_announcements boolean not null default true,
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now()
);

alter table public.notification_preferences enable row level security;
revoke all on public.notification_preferences from public, anon, authenticated;

drop trigger if exists notification_preferences_touch
  on public.notification_preferences;
create trigger notification_preferences_touch
  before update on public.notification_preferences
  for each row execute function public.touch_updated_at();

