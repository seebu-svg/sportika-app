$$;

-- Detail read. Null means "not yours or gone", so an id from another member is
-- indistinguishable from a deleted one.
create or replace function public.get_notification(p_notification_id uuid)
returns public.notifications
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_row public.notifications;
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode = '28000';
  end if;

  select * into v_row
    from public.notifications n
   where n.id = p_notification_id and n.recipient_id = v_uid;

  -- A "select into" that matches nothing leaves an all-null row behind, which
  -- is not the same as SQL null. Return a real null so the caller can tell
  -- "not yours" from "yours".
  if v_row.id is null then
    return null;
  end if;

  return v_row;
end;
$$;

create or replace function public.mark_notification_read(p_notification_id uuid)
returns public.notifications
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_row public.notifications;
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode = '28000';
  end if;

  update public.notifications
     set read_at = coalesce(read_at, now())
   where id = p_notification_id and recipient_id = v_uid
  returning * into v_row;

  -- Another member's id updates nothing; report that as a plain null.
  if v_row.id is null then
    return null;
  end if;

  return v_row;
end;
$$;

create or replace function public.mark_all_notifications_read()
returns int
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid   uuid := auth.uid();
