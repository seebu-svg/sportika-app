create or replace function public.update_notification_preferences(
  p_match_activity         boolean default null,
  p_tournament_updates     boolean default null,
  p_team_activity          boolean default null,
  p_scorer_assignments     boolean default null,
  p_platform_announcements boolean default null
)
returns public.notification_preferences
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_row public.notification_preferences;
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode = '28000';
  end if;

  -- The values are carried into the insert as well: an "on conflict do
  -- update" only fires for a row that already exists, so a first-time write
  -- has to start from the values the member just chose.
  insert into public.notification_preferences as pref (
    profile_id, match_activity, tournament_updates, team_activity,
    scorer_assignments, platform_announcements
  )
  values (
    v_uid,
    coalesce(p_match_activity, true),
    coalesce(p_tournament_updates, true),
    coalesce(p_team_activity, true),
    coalesce(p_scorer_assignments, true),
    coalesce(p_platform_announcements, true)
  )
  on conflict (profile_id) do update
     set match_activity         = coalesce(p_match_activity,
                                           pref.match_activity),
         tournament_updates     = coalesce(p_tournament_updates,
                                           pref.tournament_updates),
         team_activity          = coalesce(p_team_activity,
                                           pref.team_activity),
         scorer_assignments     = coalesce(p_scorer_assignments,
                                           pref.scorer_assignments),
         platform_announcements = coalesce(p_platform_announcements,
                                           pref.platform_announcements)
  returning * into v_row;

  return v_row;
end;
$$;

-- ════════════════════════════════════════════════════════════════════════════
-- 12. scheduled reminders and retention
-- ════════════════════════════════════════════════════════════════════════════
-- One idempotent pass over the events that are due. pg_cron calls it every five
-- minutes; the event keys make a second run in the same window a no-op.
-- Comparisons are absolute (timestamptz), so a member's timezone can never move
-- a reminder to the wrong instant.
create or replace function public.dispatch_due_notifications()
returns int
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row   record;
  v_count int := 0;
begin
  -- A match starting inside the next hour: players, organizer and scorer.
  for v_row in
    select m.id,
           m.title,
           m.scheduled_at,
           r.recipient_id,
           bool_or(r.recipient_id = m.scorer_id) as scoring
      from public.matches m
      cross join lateral public._match_recipients(m.id) r
     where m.status = 'upcoming'
       and m.scheduled_at > now()
       and m.scheduled_at <= now() + interval '60 minutes'
     group by m.id, m.title, m.scheduled_at, r.recipient_id
  loop
    if public._notify(
         v_row.recipient_id,
         case when v_row.scoring then 'scorer' else 'match' end,
         'match_starting_soon',
         case when v_row.scoring then 'Scoring duty starts soon'
              else 'Match starting soon' end,
         case when v_row.scoring
              then format('You are scoring %s, and it starts within the hour.',
                          v_row.title)
              else format('%s starts within the hour.', v_row.title)
         end,
         'match', v_row.id::text,
         jsonb_build_object('matchId', v_row.id, 'tab', 2),
         null,
         format('match_soon:%s:%s', v_row.id, v_row.recipient_id)
       ) is not null then
      v_count := v_count + 1;
    end if;
  end loop;

  -- Registration closing within the next day, for members still registered.
  if to_regclass('public.tournaments') is not null
     and to_regclass('public.tournament_entries') is not null then
    for v_row in
      select t.id, t.name, e.user_id
        from public.tournaments t
        join public.tournament_entries e on e.tournament_id = t.id
       where t.status = 'registration_open'
         and t.registration_closes_at is not null
         and t.registration_closes_at > now()
         and t.registration_closes_at <= now() + interval '24 hours'
         and e.status in ('pending', 'approved')
    loop
      if public._notify(
           v_row.user_id, 'tournament', 'tournament_registration_closing',
           'Registration closes soon',
           format('Registration for %s closes within a day.', v_row.name),
           'tournament', v_row.id::text,
           jsonb_build_object('tournamentId', v_row.id, 'tab', 1),
           null,
           format('tournament_closing:%s:%s', v_row.id, v_row.user_id)
         ) is not null then
        v_count := v_count + 1;
      end if;
    end loop;
  end if;

  -- An assigned official scoring duty within the next day.
  if to_regclass('public.tournament_matches') is not null then
    for v_row in
      select tm.id, t.name, tm.scorer_user_id
        from public.tournament_matches tm
        join public.tournaments t on t.id = tm.tournament_id
       where tm.status = 'scheduled'
         and tm.scorer_user_id is not null
         and tm.created_at <= now() + interval '24 hours'
    loop
      if public._notify(
           v_row.scorer_user_id, 'scorer', 'scorer_duty_reminder',
           'Upcoming scoring duty',
           format('You have a scheduled fixture to score at %s.', v_row.name),
           'fixture', v_row.id::text,
           jsonb_build_object('tournamentId', v_row.id, 'fixtureId', v_row.id,
                              'tab', 2),
           null,
           format('scorer_duty:%s', v_row.id)
         ) is not null then
        v_count := v_count + 1;
      end if;
    end loop;
  end if;

  return v_count;
end;
$$;

-- Retention: expired rows and read rows older than the window are removed. The
-- inbox is a feed, not an archive.
create or replace function public.purge_notifications(p_keep_days int default 90)
returns int
language plpgsql
security definer
set search_path = public
as $$
declare
  v_days int := greatest(coalesce(p_keep_days, 90), 7);
  v_count int;
begin
  with removed as (
    delete from public.notifications n
     where (n.expires_at is not null and n.expires_at < now())
        or (n.read_at is not null
            and n.read_at < now() - make_interval(days => v_days))
    returning 1
  )
  select count(*)::int into v_count from removed;

  return coalesce(v_count, 0);
end;
$$;

-- pg_cron ships with the platform but not with every local image, so the
-- schedule is installed only where the extension exists.
do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    if exists (select 1 from cron.job where jobname = 'sportika_due_notifications') then
      perform cron.unschedule('sportika_due_notifications');
    end if;
    perform cron.schedule(
      'sportika_due_notifications',
      '*/5 * * * *',
      'select public.dispatch_due_notifications()'
    );

    if exists (select 1 from cron.job where jobname = 'sportika_notification_retention') then
      perform cron.unschedule('sportika_notification_retention');
    end if;
    perform cron.schedule(
      'sportika_notification_retention',
      '17 3 * * *',
      'select public.purge_notifications()'
    );
  end if;
exception
  when others then
    raise notice 'pg_cron scheduling skipped: %', sqlerrm;
end $$;

