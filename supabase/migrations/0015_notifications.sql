-- Keyset pagination: the caller passes the last row's (created_at, id), never an
-- offset, so a new notification arriving mid-scroll cannot duplicate or skip a
-- row.
create or replace function public.list_my_notifications(
  p_limit      int default 30,
  p_before     timestamptz default null,
  p_before_id  uuid default null,
  p_unread_only boolean default false,
  p_category   text default null
)
returns setof public.notifications
language sql
stable
security definer
set search_path = public
as $$
  select n.*
    from public.notifications n
   where n.recipient_id = auth.uid()
     and (p_unread_only is not true or n.read_at is null)
     and (p_category is null or n.category = lower(p_category))
     and (p_before is null
          or (n.created_at, n.id) <
             (p_before, coalesce(p_before_id,
                                 'ffffffff-ffff-ffff-ffff-ffffffffffff'::uuid)))
     and (n.expires_at is null or n.expires_at > now())
   order by n.created_at desc, n.id desc
   limit least(greatest(coalesce(p_limit, 30), 1), 100);
$$;

