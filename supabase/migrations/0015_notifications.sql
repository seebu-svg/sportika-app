-- One switch per category. A missing row means defaults, i.e. everything on.
create or replace function public._notification_category_enabled(
  p_recipient uuid,
  p_category  text
)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select case lower(coalesce(p_category, 'platform'))
    when 'account' then true
    else coalesce((
      select case lower(coalesce(p_category, 'platform'))
        when 'match'      then pref.match_activity
        when 'dispute'    then pref.match_activity
        when 'scorer'     then pref.scorer_assignments
        when 'tournament' then pref.tournament_updates
        when 'team'       then pref.team_activity
        when 'platform'   then pref.platform_announcements
        else true
      end
        from public.notification_preferences pref
       where pref.profile_id = p_recipient
    ), true)
  end;
$$;

create or replace function public._display_name(p_profile_id uuid)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    nullif(trim((select p.display_name from public.profiles p
                  where p.id = p_profile_id)), ''),
    'A Sportika player'
  );
$$;

-- The single write path for a notification. Every trigger and RPC calls this so
-- preferences, deduplication and self-suppression are enforced in one place.
create or replace function public._notify(
  p_recipient  uuid,
  p_category   text,
  p_type       text,
  p_title      text,
  p_body       text,
  p_entity_type text default null,
  p_entity_id   text default null,
  p_payload     jsonb default '{}'::jsonb,
  p_actor       uuid default null,
  p_event_key   text default null,
  p_expires_at  timestamptz default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_category text := lower(trim(coalesce(p_category, 'platform')));
  v_title    text := left(trim(coalesce(p_title, 'Sportika')), 120);
  v_body     text := left(trim(coalesce(p_body, '')), 400);
  v_key      text := nullif(left(trim(coalesce(p_event_key, '')), 200), '');
  v_id       uuid;
begin
  if p_recipient is null then
    return null;
  end if;
  if not exists (select 1 from public.profiles p where p.id = p_recipient) then
    return null;
  end if;

  -- Your own action never notifies you, except for account/security messages,
  -- where you are exactly the member who has to know.
  if p_actor is not null
     and p_actor = p_recipient
     and v_category not in ('account', 'platform') then
    return null;
  end if;

  if not public._notification_category_enabled(p_recipient, v_category) then
    return null;
  end if;

  if v_key is not null and exists (
    select 1 from public.notifications n
     where n.recipient_id = p_recipient and n.event_key = v_key
  ) then
    return null;
  end if;

  begin
    insert into public.notifications (
      recipient_id, actor_id, category, type, title, body,
      entity_type, entity_id, payload, expires_at, event_key
    ) values (
      p_recipient, p_actor, v_category, left(trim(p_type), 60), v_title, v_body,
      p_entity_type, p_entity_id,
      case when jsonb_typeof(coalesce(p_payload, '{}'::jsonb)) = 'object'
           then coalesce(p_payload, '{}'::jsonb) else '{}'::jsonb end,
      p_expires_at, v_key
    )
    returning id into v_id;
  exception
    when unique_violation then
      -- A concurrent delivery of the same event won the race.
      return null;
  end;

  return v_id;
end;
$$;

-- Everyone who plays in or runs a match. Participants who declined or were
-- removed are excluded, so a cancelled match does not wake an old invite.
create or replace function public._match_recipients(p_match_id uuid)
returns table (recipient_id uuid)
language sql
stable
security definer
set search_path = public
as $$
  select m.organizer_id from public.matches m where m.id = p_match_id
  union
  select m.scorer_id from public.matches m
   where m.id = p_match_id and m.scorer_id is not null
  union
  select p.profile_id from public.match_participants p
   where p.match_id = p_match_id and p.status in ('invited', 'accepted');
$$;

revoke all on function public._notification_category_enabled(uuid, text)
  from public, anon, authenticated;
revoke all on function public._display_name(uuid)
  from public, anon, authenticated;
revoke all on function public._notify(
  uuid, text, text, text, text, text, text, jsonb, uuid, text, timestamptz)
  from public, anon, authenticated;
revoke all on function public._match_recipients(uuid)
  from public, anon, authenticated;

-- ════════════════════════════════════════════════════════════════════════════
-- 4.  generation: match participants
-- ════════════════════════════════════════════════════════════════════════════
create or replace function public.notify_match_participant_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_match public.matches;
begin
  select * into v_match from public.matches where id = new.match_id;
  if v_match.id is null then
    return null;
  end if;

  if tg_op = 'INSERT' then
    if new.status = 'invited' then
      perform public._notify(
        new.profile_id, 'match', 'match_invite', 'Match invitation',
        format('%s invited you to %s.', public._display_name(new.invited_by),
               v_match.title),
        'match', v_match.id::text,
        jsonb_build_object('matchId', v_match.id, 'tab', 2),
        new.invited_by,
        format('match_invite:%s:%s:%s', new.match_id, new.profile_id,
               to_char(new.created_at at time zone 'UTC', 'YYMMDDHH24MISSUS'))
      );
    end if;
    return null;
  end if;

  if new.status is not distinct from old.status then
    return null;
  end if;

  if new.status = 'accepted' then
    perform public._notify(
      v_match.organizer_id, 'match', 'match_invite_accepted',
      'Invitation accepted',
      format('%s joined %s.', public._display_name(new.profile_id),
             v_match.title),
      'match', v_match.id::text,
      jsonb_build_object('matchId', v_match.id, 'tab', 2),
      new.profile_id,
      format('match_invite_answered:%s:%s:%s', new.match_id, new.profile_id,
             to_char(new.updated_at at time zone 'UTC', 'YYMMDDHH24MISSUS'))
    );
  elsif new.status = 'declined' then
    perform public._notify(
      v_match.organizer_id, 'match', 'match_invite_declined',
      'Invitation declined',
      format('%s cannot make %s.', public._display_name(new.profile_id),
             v_match.title),
      'match', v_match.id::text,
      jsonb_build_object('matchId', v_match.id, 'tab', 2),
      new.profile_id,
      format('match_invite_answered:%s:%s:%s', new.match_id, new.profile_id,
             to_char(new.updated_at at time zone 'UTC', 'YYMMDDHH24MISSUS'))
    );
  elsif new.status = 'removed' then
    perform public._notify(
      new.profile_id, 'match', 'match_removed',
      'Removed from a match',
      format('You are no longer part of %s.', v_match.title),
      'match', v_match.id::text,
      jsonb_build_object('matchId', v_match.id, 'tab', 2),
      auth.uid(),
      format('match_removed:%s:%s:%s', new.match_id, new.profile_id,
             to_char(new.updated_at at time zone 'UTC', 'YYMMDDHH24MISSUS'))
    );
  end if;

  return null;
end;
$$;

drop trigger if exists notify_match_participant_change
  on public.match_participants;
create trigger notify_match_participant_change
  after insert or update of status on public.match_participants
  for each row execute function public.notify_match_participant_change();

-- ════════════════════════════════════════════════════════════════════════════
-- 5.  generation: match lifecycle, scorer transfer, schedule
-- ════════════════════════════════════════════════════════════════════════════
create or replace function public.notify_match_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid  uuid := auth.uid();
  v_row  record;
  v_stamp text := to_char(now() at time zone 'UTC', 'YYMMDDHH24MISSUS');
  v_when text;
begin
  -- ── scorer assigned / revoked on the match itself ──────────────────────
  if new.scorer_id is distinct from old.scorer_id then
    if new.scorer_id is not null then
      perform public._notify(
        new.scorer_id, 'scorer', 'scorer_assigned',
        'You are the official scorer',
        format('You have been assigned to score %s.', new.title),
        'match', new.id::text,
        jsonb_build_object('matchId', new.id, 'tab', 2),
        v_uid,
        format('scorer_assigned:%s:%s', new.id, v_stamp)
      );
    end if;
    if old.scorer_id is not null and old.scorer_id is distinct from new.scorer_id then
      perform public._notify(
        old.scorer_id, 'scorer', 'scorer_assignment_revoked',
        'Scoring assignment removed',
        format('You are no longer the official scorer for %s.', new.title),
        'match', new.id::text,
        jsonb_build_object('matchId', new.id, 'tab', 2),
        v_uid,
        format('scorer_revoked:%s:%s', new.id, v_stamp)
      );
    end if;
  end if;

  -- ── schedule moved ─────────────────────────────────────────────────────
  if new.scheduled_at is distinct from old.scheduled_at then
    v_when := to_char(new.scheduled_at at time zone 'UTC',
                      'Dy DD Mon YYYY, HH24:MI "UTC"');
    for v_row in
      select recipient_id from public._match_recipients(new.id)
    loop
      perform public._notify(
        v_row.recipient_id, 'match', 'match_schedule_changed',
        'Match schedule changed',
        format('%s is now scheduled for %s.', new.title, v_when),
        'match', new.id::text,
        jsonb_build_object('matchId', new.id, 'tab', 2),
        v_uid,
        format('match_schedule:%s:%s:%s', new.id, v_row.recipient_id,
               to_char(new.scheduled_at at time zone 'UTC',
                       'YYMMDDHH24MISS'))
      );
    end loop;
  end if;

  -- ── status transitions ─────────────────────────────────────────────────
  if new.status is distinct from old.status then
    if new.status = 'cancelled' then
      for v_row in
        select recipient_id from public._match_recipients(new.id)
      loop
        perform public._notify(
          v_row.recipient_id, 'match', 'match_cancelled', 'Match cancelled',
          format('%s has been cancelled.', new.title),
          'match', new.id::text,
          jsonb_build_object('matchId', new.id, 'tab', 2),
          v_uid,
          format('match_cancelled:%s:%s', new.id, v_row.recipient_id)
        );
      end loop;

    elsif new.status = 'live' then
      if new.scorer_id is not null then
        perform public._notify(
          new.scorer_id, 'scorer', 'scorer_match_started', 'Match started',
          format('The match you are scoring, %s, has started.', new.title),
          'match', new.id::text,
          jsonb_build_object('matchId', new.id, 'tab', 2),
          v_uid,
          format('scorer_match_started:%s:%s', new.id, v_stamp)
        );
      end if;

    elsif new.status = 'submitted' then
      perform public._notify(
        new.organizer_id, 'match', 'match_result_submitted',
        'Result ready for review',
        format('The result of %s was submitted. Publish it to make it official.',
               new.title),
        'match', new.id::text,
        jsonb_build_object('matchId', new.id, 'tab', 2),
        v_uid,
        format('match_submitted:%s:%s', new.id, v_stamp)
      );
      if new.scorer_id is not null then
        perform public._notify(
          new.scorer_id, 'scorer', 'scorer_match_completed', 'Match completed',
          format('You finished scoring %s.', new.title),
          'match', new.id::text,
          jsonb_build_object('matchId', new.id, 'tab', 2),
          v_uid,
          format('scorer_match_completed:%s:%s', new.id, v_stamp)
        );
      end if;

    elsif new.status in ('published', 'walkover') then
      for v_row in
        select recipient_id from public._match_recipients(new.id)
      loop
        perform public._notify(
          v_row.recipient_id,
          case when new.status = 'walkover' then 'match' else 'match' end,
          'result_published', 'Result published',
          format('The official result of %s is out.', new.title),
          'result', new.id::text,
          jsonb_build_object('matchId', new.id, 'tab', 2),
          v_uid,
          format('result_published:%s:%s', new.id, v_row.recipient_id)
        );
      end loop;
    end if;
  end if;

  return null;
end;
$$;

drop trigger if exists notify_match_change on public.matches;
create trigger notify_match_change
  after update of status, scheduled_at, scorer_id on public.matches
  for each row execute function public.notify_match_change();

-- A published result that is later corrected is news for everyone who played.
create or replace function public.notify_match_result_correction()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_match public.matches;
  v_row   record;
begin
  select * into v_match from public.matches where id = new.match_id;
  if v_match.id is null then
    return null;
  end if;

  for v_row in
    select recipient_id from public._match_recipients(new.match_id)
  loop
    perform public._notify(
      v_row.recipient_id, 'match', 'result_corrected', 'Result corrected',
      format('The published result of %s was corrected.', v_match.title),
      'result', v_match.id::text,
      jsonb_build_object('matchId', v_match.id, 'tab', 2),
      new.changed_by,
      format('result_corrected:%s:%s', new.id, v_row.recipient_id)
    );
  end loop;

  return null;
end;
$$;

drop trigger if exists notify_match_result_correction
  on public.match_result_corrections;
create trigger notify_match_result_correction
  after insert on public.match_result_corrections
  for each row execute function public.notify_match_result_correction();

-- ════════════════════════════════════════════════════════════════════════════
-- 6.  generation: disputes
-- ════════════════════════════════════════════════════════════════════════════
create or replace function public.notify_match_dispute_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_match public.matches;
  v_stamp text := to_char(now() at time zone 'UTC', 'YYMMDDHH24MISSUS');
  v_title text;
  v_body  text;
begin
  select * into v_match from public.matches where id = new.match_id;
  if v_match.id is null then
    return null;
  end if;

  if tg_op = 'INSERT' then
    perform public._notify(
      v_match.organizer_id, 'dispute', 'dispute_submitted', 'Dispute raised',
      format('A result dispute was raised on %s.', v_match.title),
      'dispute', new.id::text,
      jsonb_build_object('matchId', v_match.id, 'disputeId', new.id, 'tab', 2),
      new.raised_by,
      format('dispute_raised:%s:%s', new.id, v_match.organizer_id)
    );
    if v_match.scorer_id is not null
       and v_match.scorer_id is distinct from v_match.organizer_id then
      perform public._notify(
        v_match.scorer_id, 'dispute', 'dispute_submitted', 'Dispute raised',
        format('A result dispute was raised on %s.', v_match.title),
        'dispute', new.id::text,
        jsonb_build_object('matchId', v_match.id, 'disputeId', new.id, 'tab', 2),
        new.raised_by,
        format('dispute_raised:%s:%s', new.id, v_match.scorer_id)
      );
    end if;
    return null;
  end if;

  if new.status is not distinct from old.status then
    return null;
  end if;

  if new.status = 'resolved' then
    v_title := 'Dispute resolved';
  elsif new.status = 'rejected' then
    v_title := 'Dispute closed';
  else
    v_title := 'Dispute under review';
  end if;

  v_body := case new.status
    when 'resolved' then
      format('Your dispute on %s was resolved.', v_match.title)
    when 'rejected' then
      format('Your dispute on %s was reviewed and closed.', v_match.title)
    else
      format('Your dispute on %s is being reviewed.', v_match.title)
  end;

  perform public._notify(
    new.raised_by, 'dispute',
    case new.status
      when 'resolved' then 'dispute_resolved'
      when 'rejected' then 'dispute_rejected'
      else 'dispute_status_changed'
    end,
    v_title, v_body,
    'dispute', new.id::text,
    jsonb_build_object('matchId', v_match.id, 'disputeId', new.id, 'tab', 2),
    auth.uid(),
    format('dispute_status:%s:%s:%s', new.id, new.status, v_stamp)
  );

  return null;
end;
$$;

drop trigger if exists notify_match_dispute_change on public.match_disputes;
create trigger notify_match_dispute_change
  after insert or update of status on public.match_disputes
  for each row execute function public.notify_match_dispute_change();

-- ════════════════════════════════════════════════════════════════════════════
-- 7.  generation: tournament-keyed scorer assignments (0006 surface)
-- ════════════════════════════════════════════════════════════════════════════
create or replace function public.notify_scorer_assignment_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_stamp text := to_char(now() at time zone 'UTC', 'YYMMDDHH24MISSUS');
  v_payload jsonb;
begin
  v_payload := jsonb_build_object(
    'tournamentId', new.tournament_id,
    'fixtureId', new.fixture_id,
    'tab', 2
  );

  if tg_op = 'INSERT' then
    perform public._notify(
      new.scorer_profile_id, 'scorer', 'scorer_fixture_assigned',
      'Scoring duty assigned',
      'You have been assigned as the official scorer for a tournament fixture.',
      'fixture', new.fixture_id, v_payload, new.authorized_by,
      format('scorer_fixture_assigned:%s:%s', new.id, v_stamp)
    );
    return null;
  end if;

  if new.status is distinct from old.status then
    if new.status = 'revoked' then
      perform public._notify(
        new.scorer_profile_id, 'scorer', 'scorer_assignment_revoked',
        'Scoring duty removed',
        'You are no longer assigned to that tournament fixture.',
        'fixture', new.fixture_id, v_payload, auth.uid(),
        format('scorer_fixture_revoked:%s:%s', new.id, v_stamp)
      );
    elsif new.status in ('accepted', 'declined') then
      perform public._notify(
        new.authorized_by, 'scorer', 'scorer_assignment_response',
